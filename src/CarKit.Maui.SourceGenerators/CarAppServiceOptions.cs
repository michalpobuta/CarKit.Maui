using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis.Diagnostics;

namespace CarKit.Maui.SourceGenerators;

// Generator input: values computed by buildTransitive/CarKit.Maui.targets (the only category mapping table). Comparable
// by value, so the incremental generator does not regenerate without changes.
internal sealed class CarAppServiceOptions : IEquatable<CarAppServiceOptions>
{
    private const string Prefix = "build_property.";
    // A comma from the targets (.editorconfig truncates the value at ';'); a semicolon stays for input from outside the
    // targets (tests)
    private static readonly char[] _separators = [',', ';'];

    private CarAppServiceOptions(
        bool generate,
        IReadOnlyList<string> intentCategories,
        IReadOnlyList<string> permissions,
        int minCarApiLevel,
        bool automotiveDescriptor,
        bool mediaService,
        IReadOnlyList<string> mediaPermissions,
        bool messageReceiver,
        IReadOnlyList<string> messagePermissions)
    {
        MessageReceiver = messageReceiver;
        MessagePermissions = messagePermissions;
        Generate = generate;
        IntentCategories = intentCategories;
        Permissions = permissions;
        MinCarApiLevel = minCarApiLevel;
        AutomotiveDescriptor = automotiveDescriptor;
        MediaService = mediaService;
        MediaPermissions = mediaPermissions;
    }

    public bool Generate { get; }

    public IReadOnlyList<string> IntentCategories { get; }

    public IReadOnlyList<string> Permissions { get; }

    public int MinCarApiLevel { get; }

    public bool AutomotiveDescriptor { get; }

    // Stage 5: Audio with the Media module — the CarKitMediaLibraryService service (Media3) and its foreground
    // permissions
    public bool MediaService { get; }

    public IReadOnlyList<string> MediaPermissions { get; }

    // Stage 6: Communication with the module — the notification action receiver (CarKitMessageActionReceiver) and
    // POST_NOTIFICATIONS
    public bool MessageReceiver { get; }

    public IReadOnlyList<string> MessagePermissions { get; }

    public static CarAppServiceOptions From(AnalyzerConfigOptions options) => new(
        IsTrue(Read(options, "CarKitAndroidGenerateService")),
        List(Read(options, "CarKitAndroidIntentCategories")),
        List(Read(options, "CarKitAndroidPermissions")),
        int.TryParse(Read(options, "CarKitAndroidMinCarApiLevel"), NumberStyles.Integer, CultureInfo.InvariantCulture, out var level) && level >= 1 ? level : 1,
        IsTrue(Read(options, "CarKitAndroidAutomotiveDescriptor")),
        IsTrue(Read(options, "CarKitAndroidMediaService")),
        List(Read(options, "CarKitAndroidMediaPermissions")),
        IsTrue(Read(options, "CarKitAndroidMessageReceiver")),
        List(Read(options, "CarKitAndroidMessagePermissions")));

    // null = nothing to generate (another platform, a library or no Android Auto category)
    public string? Render(string generatorVersion)
    {
        var service = IntentCategories.Count > 0;
        if (!Generate || (!service && !AutomotiveDescriptor && !MediaService && !MessageReceiver))
        {
            return null;
        }

        var source = new StringBuilder()
            .AppendLine("// <auto-generated/>")
            .AppendLine("// Generated by CarKit.Maui.SourceGenerators from the CarKit* MSBuild properties of the app project.")
            .AppendLine("#nullable enable")
            .AppendLine();
        if (AutomotiveDescriptor)
        {
            source.AppendLine("[assembly: global::Android.App.MetaData(\"com.google.android.gms.car.application\", Resource = \"@xml/automotive_app_desc\")]");
        }

        if (service)
        {
            source.Append("[assembly: global::Android.App.MetaData(\"androidx.car.app.minCarApiLevel\", Value = \"")
                .Append(MinCarApiLevel.ToString(CultureInfo.InvariantCulture))
                .AppendLine("\")]");
        }

        foreach (var permission in (service ? Permissions : []).Concat(MediaService ? MediaPermissions : []).Concat(MessageReceiver ? MessagePermissions : []).Distinct(StringComparer.Ordinal))
        {
            source.Append("[assembly: global::Android.App.UsesPermission(").Append(Literal(permission)).AppendLine(")]");
        }

        if (!service && !MediaService && !MessageReceiver)
        {
            return source.ToString();
        }

        source.AppendLine()
            .AppendLine("namespace CarKit.Maui.Generated")
            .AppendLine("{");
        if (service)
        {
            source
                .AppendLine("    /// <summary>The car app service the Android Auto host binds to, generated from the CarKit categories of the app.</summary>")
                .AppendLine("    [global::Android.App.Service(Name = \"carkit.maui.generated.CarKitGeneratedAppService\", Exported = true)]")
                .Append("    [global::Android.App.IntentFilter(new[] { \"androidx.car.app.CarAppService\" }, Categories = new[] { ")
                .Append(string.Join(", ", IntentCategories.Select(Literal)))
                .AppendLine(" })]")
                .Append("    [global::System.CodeDom.Compiler.GeneratedCode(\"CarKit.Maui.SourceGenerators\", ").Append(Literal(generatorVersion)).AppendLine(")]")
                .AppendLine("    internal sealed class CarKitGeneratedAppService : global::CarKit.Maui.CarKitAppServiceBase")
                .AppendLine("    {")
                .AppendLine("    }");
        }

        if (MediaService)
        {
            // Android Auto connects to a MediaBrowserService (legacy) or a MediaLibraryService (Media3) — both in one
            // filter
            source
                .AppendLine("    /// <summary>The media library service Android Auto binds to, generated for the Audio category.</summary>")
                .AppendLine("    [global::Android.App.Service(Name = \"carkit.maui.generated.CarKitGeneratedMediaLibraryService\", Exported = true, ForegroundServiceType = global::Android.Content.PM.ForegroundService.TypeMediaPlayback)]")
                .AppendLine("    [global::Android.App.IntentFilter(new[] { \"androidx.media3.session.MediaLibraryService\", \"android.media.browse.MediaBrowserService\" })]")
                .Append("    [global::System.CodeDom.Compiler.GeneratedCode(\"CarKit.Maui.SourceGenerators\", ").Append(Literal(generatorVersion)).AppendLine(")]")
                .AppendLine("    internal sealed class CarKitGeneratedMediaLibraryService : global::CarKit.Maui.Media.CarKitMediaLibraryService")
                .AppendLine("    {")
                .AppendLine("    }");
        }

        if (MessageReceiver)
        {
            // Reply and Mark as read actions of MessagingStyle notifications (a PendingIntent with an explicit
            // component, no filters)
            source
                .AppendLine("    /// <summary>The receiver of the Reply and Mark as read actions of CarKit message notifications.</summary>")
                .AppendLine("    [global::Android.Content.BroadcastReceiver(Name = \"carkit.maui.generated.CarKitGeneratedMessageReceiver\", Exported = false)]")
                .Append("    [global::System.CodeDom.Compiler.GeneratedCode(\"CarKit.Maui.SourceGenerators\", ").Append(Literal(generatorVersion)).AppendLine(")]")
                .AppendLine("    internal sealed class CarKitGeneratedMessageReceiver : global::CarKit.Maui.Communication.CarKitMessageActionReceiver")
                .AppendLine("    {")
                .AppendLine("    }");
        }

        return source.AppendLine("}").ToString();
    }

    public bool Equals(CarAppServiceOptions? other) =>
        other is not null
        && Generate == other.Generate
        && MinCarApiLevel == other.MinCarApiLevel
        && AutomotiveDescriptor == other.AutomotiveDescriptor
        && MediaService == other.MediaService
        && MediaPermissions.SequenceEqual(other.MediaPermissions, StringComparer.Ordinal)
        && MessageReceiver == other.MessageReceiver
        && MessagePermissions.SequenceEqual(other.MessagePermissions, StringComparer.Ordinal)
        && IntentCategories.SequenceEqual(other.IntentCategories, StringComparer.Ordinal)
        && Permissions.SequenceEqual(other.Permissions, StringComparer.Ordinal);

    public override bool Equals(object? obj) => Equals(obj as CarAppServiceOptions);

    public override int GetHashCode() =>
        StringComparer.Ordinal.GetHashCode(string.Join(";", IntentCategories)) ^ MinCarApiLevel ^ (Generate ? 1 : 0) ^ (AutomotiveDescriptor ? 2 : 0) ^ (MediaService ? 4 : 0) ^ (MessageReceiver ? 8 : 0);

    private static string? Read(AnalyzerConfigOptions options, string name) =>
        options.TryGetValue(Prefix + name, out var value) ? value : null;

    private static bool IsTrue(string? value) => string.Equals(value?.Trim(), "true", StringComparison.OrdinalIgnoreCase);

    private static string[] List(string? value) =>
        [.. (value ?? string.Empty).Split(_separators, StringSplitOptions.RemoveEmptyEntries).Select(v => v.Trim()).Where(v => v.Length > 0).Distinct(StringComparer.Ordinal)];

    private static string Literal(string value) => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
}
